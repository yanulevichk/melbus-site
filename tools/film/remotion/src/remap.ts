// Перемонтаж фильма: своя скорость для каждой сцены, плавные разгоны/торможения.
// Время — в секундах ИСХОДНОГО фильма (42 с, 24 к/с, 1008 кадров).
export const FPS = 24;          // частота нового ролика
export const SRC_FPS = 72;      // исходник с дорисованными кадрами (24 → 72 к/с)
export const SRC_FRAMES = 3019; // кадров в исходнике 72 к/с
const SRC_END = 41.95;

// [начало, конец, скорость]: >1 — быстрее, <1 — замедление (кадры между исходными дорисованы, 72 к/с)
export const SEGMENTS: [number, number, number][] = [
  [0.0, 3.2, 2.6],    // влёт над жилым комплексом — быстро
  [3.2, 4.6, 1.0],    // подлетаем к квартире
  [4.6, 7.6, 1.8],    // пролёт по квартире
  [7.6, 8.6, 2.0],    // кран вверх
  [8.6, 10.6, 1.3],   // заготовка складывается в коробку
  [10.6, 11.7, 2.5],
  [11.7, 12.6, 0.55], // ЗАМЕДЛЕНИЕ: кровать ныряет в коробку
  [12.6, 18.4, 4.0],  // остальная мебель — очень быстро
  [18.4, 19.5, 2.5],  // клапаны закрываются
  [19.5, 20.7, 0.75], // ЗАМЕДЛЕНИЕ: рулон бирюзового скотча
  [20.7, 25.0, 3.0],  // бус, коробка, пандус — быстро
  [25.0, 25.6, 0.5],  // ЗАМЕДЛЕНИЕ: двери с логотипом закрываются
  [25.6, 27.8, 3.0],  // бус уезжает
  [27.8, 29.0, 0.5],  // ЗАМЕДЛЕНИЕ: камера под днищем
  [29.0, 32.0, 3.0],  // подъём, город → пригород
  [32.0, 35.8, 3.2],  // выгрузка
  [35.8, 36.7, 0.6],  // ЗАМЕДЛЕНИЕ: коробка открывается в новом доме
  [36.7, 40.6, 2.8],  // вещи разлетаются по местам — быстро
  [40.6, 42.0, 0.9],  // финальный общий план — плавно
];
const BLEND = 0.2; // сек исходника: плавный разгон/торможение на стыке сцен

const smooth = (x: number) => {
  const k = Math.min(1, Math.max(0, x));
  return k * k * (3 - 2 * k);
};

export const speedAt = (t: number): number => {
  let v = SEGMENTS[SEGMENTS.length - 1][2];
  for (const [a, b, s] of SEGMENTS) {
    if (t >= a && t < b) { v = s; break; }
  }
  for (let j = 1; j < SEGMENTS.length; j++) {
    const at = SEGMENTS[j][0];
    if (Math.abs(t - at) < BLEND) {
      const k = smooth((t - at + BLEND) / (2 * BLEND));
      v = SEGMENTS[j - 1][2] + (SEGMENTS[j][2] - SEGMENTS[j - 1][2]) * k;
    }
  }
  return v;
};

// SRC_AT[f] — какое место исходника (в секундах) показывать в кадре f нового ролика
export const SRC_AT: number[] = (() => {
  const out = [0];
  let t = 0;
  const sub = 32, dt = 1 / FPS / sub;
  while (t < SRC_END) {
    for (let k = 0; k < sub; k++) t += speedAt(t) * dt;
    out.push(Math.min(t, SRC_END));
  }
  return out;
})();

export const DURATION = SRC_AT.length - 1;
